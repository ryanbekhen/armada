//! The command line reference (docs/cli) written from the command tree, as
//! Go's internal/clidoc writes it from cobra's: an index page and one page
//! per noun. client/tests/clidoc.rs checks the pages equal the ones `make
//! docs` writes from Go's commands.

use std::collections::BTreeMap;

use super::flags::{Flag, unquote_usage};
use super::{Node, Tree};

const GENERATED: &str = "<!-- Generated by `make docs` from the commands; do not edit. -->";

/// IsAvailableCommand as the reference sees it: nouns have no run of their
/// own there (Go's refuse their unknown verbs only once the tree runs).
fn visible(t: &Tree, i: usize) -> Vec<usize> {
    let mut out: Vec<usize> = t.nodes[i]
        .children
        .iter()
        .copied()
        .filter(|&c| {
            let n = &t.nodes[c];
            !n.hidden
                && !n.removed
                && n.name() != "help"
                && n.name() != "completion"
                && (n.run.is_some() || !visible(t, c).is_empty())
        })
        .collect();
    out.sort_by(|a, b| t.nodes[*a].name().cmp(t.nodes[*b].name()));
    out
}

/// UseLine before the command ever ran: [flags] only for a command that
/// declares flags of its own.
fn use_line(t: &Tree, i: usize) -> String {
    let n = &t.nodes[i];
    let mut line = match n.parent {
        Some(p) => format!("{} {}", t.path(p), n.use_),
        None => n.use_.clone(),
    };
    if !n.disable_flags_in_use_line
        && n.flags.iter().any(|f| !f.hidden)
        && !line.contains("[flags]")
    {
        line.push_str(" [flags]");
    }
    line
}

fn cell(s: &str) -> String {
    s.trim().replace('|', "\\|").replace('\n', " ")
}

fn anchor(path: &str) -> String {
    path.to_lowercase().replace(' ', "-")
}

/// dedent: the smallest indentation of a line that is not blank, taken
/// off every line that has it.
fn dedent(s: &str) -> String {
    let lines: Vec<&str> = s.split('\n').collect();
    let mut pad: Option<usize> = None;
    for l in &lines {
        if l.trim().is_empty() {
            continue;
        }
        let n = l.len() - l.trim_start_matches([' ', '\t']).len();
        pad = Some(pad.map_or(n, |p| p.min(n)));
    }
    let pad = pad.unwrap_or(0);
    lines
        .iter()
        .map(|l| {
            if l.len() >= pad && pad > 0 {
                &l[pad..]
            } else {
                *l
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

/// flagTable: the flags sorted by name, help and hidden ones left out.
fn flag_table(flags: &[Flag]) -> String {
    let mut flags: Vec<&Flag> = flags
        .iter()
        .filter(|f| !f.hidden && f.name != "help")
        .collect();
    flags.sort_by(|a, b| a.name.cmp(&b.name));
    let mut rows = Vec::new();
    for f in flags {
        let mut name = format!("`--{}", f.name);
        if let Some(c) = f.shorthand {
            name = format!("`-{c}`, {name}");
        }
        let (varname, usage) = unquote_usage(f);
        if !varname.is_empty() {
            name.push(' ');
            name.push_str(&varname);
        }
        name.push('`');
        let def = if f.name == "config" {
            // Depends on the machine: see config::default_path.
            "$ARMADA_CONFIG, else ~/.armada/config if it exists, else /etc/armada/admin.config"
                .to_string()
        } else {
            f.def_value.clone()
        };
        let mut row = format!("| {name} | {}", cell(&usage));
        if !def.is_empty() && !["false", "[]", "0", "0s"].contains(&def.as_str()) {
            row.push_str(&format!(" (default `{def}`)"));
        }
        row.push_str(" |");
        rows.push(row);
    }
    if rows.is_empty() {
        return String::new();
    }
    format!("| Flag | Meaning |\n| --- | --- |\n{}\n", rows.join("\n"))
}

fn has_parent_noun(t: &Tree, n: &Node) -> bool {
    n.parent.is_some_and(|p| t.nodes[p].parent.is_some())
}

fn write_command(b: &mut String, t: &Tree, i: usize, level: usize) {
    let n = &t.nodes[i];
    if level > 2 || has_parent_noun(t, n) {
        b.push_str(&format!("{} `{}`\n\n", "#".repeat(level.min(4)), t.path(i)));
    }
    let mut desc = n.long.trim().to_string();
    if desc.is_empty() {
        desc = n.short.trim().to_string();
        if !desc.is_empty() && !desc.ends_with('.') {
            desc.push('.');
        }
    }
    if !desc.is_empty() {
        b.push_str(&format!("{desc}\n\n"));
    }
    let runnable = n.run.is_some();
    if runnable {
        b.push_str(&format!("```\n{}\n```\n\n", use_line(t, i)));
    }
    if !n.aliases.is_empty() {
        b.push_str(&format!("Also: `{}`.\n\n", n.aliases.join("`, `")));
    }
    let subs = visible(t, i);
    if !subs.is_empty() && !runnable {
        b.push_str("| Command | What it does |\n| --- | --- |\n");
        for s in subs {
            let p = t.path(s);
            b.push_str(&format!(
                "| [`{p}`](#{}) | {} |\n",
                anchor(&p),
                cell(&t.nodes[s].short)
            ));
        }
        b.push('\n');
    }
    if !n.example.is_empty() {
        b.push_str(&format!(
            "Examples:\n\n```bash\n{}\n```\n\n",
            dedent(&n.example).trim_matches('\n')
        ));
    }
    let table = flag_table(&n.flags);
    if !table.is_empty() && runnable {
        b.push_str(&format!("Flags:\n\n{table}\n"));
    }
}

fn write_tree(b: &mut String, t: &Tree, i: usize, level: usize) {
    write_command(b, t, i, level);
    for s in visible(t, i) {
        write_tree(b, t, s, level + 1);
    }
}

/// Pages: the index (armada.md) and one page per noun (armada-NOUN.md),
/// keyed by file name.
pub fn pages(t: &Tree) -> BTreeMap<String, String> {
    let root = &t.nodes[0];
    let name = root.name().to_string();
    let mut pages = BTreeMap::new();
    let mut index = format!("# `{name}`\n\n{GENERATED}\n\n");
    if !root.long.is_empty() {
        index.push_str(&format!("{}\n\n", root.long.trim()));
    } else if !root.short.is_empty() {
        index.push_str(&format!("{}.\n\n", root.short.trim().trim_end_matches('.')));
    }
    let globals = flag_table(&root.persistent);
    if !globals.is_empty() {
        index.push_str(&format!(
            "## Global flags\n\nEvery command takes these.\n\n{globals}\n"
        ));
    }
    index.push_str("## Commands\n\n| Command | What it does |\n| --- | --- |\n");
    for c in visible(t, 0) {
        let noun = t.nodes[c].name();
        let file = format!("{name}-{noun}.md");
        index.push_str(&format!(
            "| [`{name} {noun}`]({file}) | {} |\n",
            cell(&t.nodes[c].short)
        ));
        let mut page = format!(
            "# `{}`\n\n{GENERATED}\n\n[All commands]({name}.md)\n\n",
            t.path(c)
        );
        write_command(&mut page, t, c, 2);
        for s in visible(t, c) {
            write_tree(&mut page, t, s, 2);
        }
        pages.insert(file, page);
    }
    pages.insert(format!("{name}.md"), index);
    pages
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::cli::flags::Value;

    #[test]
    fn dedents() {
        assert_eq!(dedent("  a\n    b\n\n  c"), "a\n  b\n\nc");
    }

    #[test]
    fn slices_list_no_default() {
        let f = Flag::string_slice("to", None, "recipients");
        assert!(matches!(f.value, Value::StrSlice(_)));
        assert_eq!(
            flag_table(&[f]),
            "| Flag | Meaning |\n| --- | --- |\n| `--to strings` | recipients |\n"
        );
    }
}
