//! armadad runtime: the runtime pack installed, and on containerd nodes
//! containerd run (Go's runtime.go and embedded.Exec).

use std::os::unix::process::CommandExt;

use armada_client::cli::{Ctx, Error, Result};

use crate::agentconfig::{self, RUNTIME_SUPERVISOR};
use crate::pack::{self, Paths};

pub fn run(ctx: &mut Ctx<'_>, _: &[String]) -> Result {
    let data_dir = ctx.str("data-dir");
    let bin_dir = ctx.str("bin-dir");
    let ac = match agentconfig::load(&data_dir) {
        Err(e) if e.not_found => {
            let _ = writeln!(ctx.err, "{data_dir} is not initialized; nothing to run");
            return Ok(());
        }
        r => r?,
    };
    ac.check_runtime()?;
    let p = crate::paths(&data_dir);
    if ac.runtime == RUNTIME_SUPERVISOR {
        if !bin_dir.is_empty() {
            pack::use_bin_dir(&p.bundle(), &bin_dir)?;
        }
        pack::install_pack(&p)?;
        let _ = writeln!(
            ctx.err,
            "this node runs containers without containerd (runtime: supervisor); the runtime pack is installed, nothing to run"
        );
        return Ok(());
    }
    Err(Error::Msg(exec_containerd(&p, pack::bundled(), &bin_dir)))
}

/// embedded.Exec: the pack and configuration prepared, then this process
/// replaced with containerd. It returns only on failure.
fn exec_containerd(p: &Paths, pack: &[u8], bin_dir: &str) -> String {
    let prepared = (|| -> std::result::Result<(), String> {
        pack::check_host()?;
        if !pack.is_empty() {
            pack::install(&p.bundle(), pack)?;
        } else if !bin_dir.is_empty() {
            pack::use_bin_dir(&p.bundle(), bin_dir)?;
        } else {
            return Err("this binary has no runtime bundle; build with `make build-bundle` or pass --bin-dir".to_string());
        }
        for d in [p.root(), p.state(), p.logs(), p.containers(), p.cni()] {
            crate::gofs::mkdir_all(&d, 0o700)?;
        }
        armada_fsutil::write_file_atomic(&p.config(), containerd_config(p).as_bytes(), 0o600)
            .map_err(|e| e.to_string())
    })();
    if let Err(e) = prepared {
        return e;
    }
    let bin = p.bin().join(pack::BIN_CONTAINERD);
    let path = format!(
        "PATH={}:/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin",
        p.bin().display()
    );
    let (k, v) = path.split_once('=').expect("PATH=");
    let err = std::process::Command::new(&bin)
        .arg0("containerd")
        .arg("--config")
        .arg(p.config())
        .env_clear()
        .env(k, v)
        .exec();
    format!("exec containerd: {}", armada_fsutil::errno_text(&err))
}

/// disabledPlugins.
const DISABLED_PLUGINS: [&str; 10] = [
    "io.containerd.grpc.v1.cri",
    "io.containerd.cri.v1.images",
    "io.containerd.cri.v1.runtime",
    "io.containerd.podsandbox.controller.v1.podsandbox",
    "io.containerd.nri.v1.nri",
    "io.containerd.server.v1.grpc-tcp",
    "io.containerd.server.v1.debug",
    "io.containerd.server.v1.metrics",
    "io.containerd.http.v1.pprof",
    "io.containerd.monitor.container.v1.restart",
];

/// ContainerdConfig.
pub fn containerd_config(p: &Paths) -> String {
    let q = |s: &str| armada_spec::go::quote(s);
    let plugins: Vec<String> = DISABLED_PLUGINS.iter().map(|d| q(d)).collect();
    let mut b = String::new();
    b.push_str("# Generated by Armada (ADR 0011); changes are overwritten.\n");
    b.push_str("version = 4\n");
    b.push_str(&format!("root = {}\n", q(&p.root().to_string_lossy())));
    b.push_str(&format!("state = {}\n", q(&p.state().to_string_lossy())));
    b.push_str("imports = []\n");
    b.push_str(&format!("disabled_plugins = [{}]\n\n", plugins.join(", ")));
    b.push_str("[plugins]\n");
    let socket = p.socket().to_string_lossy().into_owned();
    b.push_str(&format!(
        "  [plugins.{}]\n    address = {}\n    uid = 0\n    gid = 0\n",
        q("io.containerd.server.v1.grpc"),
        q(&socket)
    ));
    b.push_str(&format!(
        "  [plugins.{}]\n    address = {}\n    uid = 0\n    gid = 0\n",
        q("io.containerd.server.v1.ttrpc"),
        q(&format!("{socket}.ttrpc"))
    ));
    b
}
