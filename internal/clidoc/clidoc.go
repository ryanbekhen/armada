// Package clidoc writes the command line reference (docs/cli) from the
// commands themselves, so it never drifts from them.
package clidoc

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"
)

// Pages renders the reference of root: an index page (<root>.md) and one
// page per command group under root (<root>-<group>.md), keyed by file
// name.
func Pages(root *cobra.Command) map[string][]byte {
	root.InitDefaultHelpCmd()
	root.InitDefaultCompletionCmd()
	name := root.Name()
	pages := map[string][]byte{}
	var index bytes.Buffer
	fmt.Fprintf(&index, "# `%s`\n\n<!-- Generated by `make docs` from the commands; do not edit. -->\n\n", name)
	if root.Long != "" {
		fmt.Fprintf(&index, "%s\n\n", strings.TrimSpace(root.Long))
	} else if root.Short != "" {
		fmt.Fprintf(&index, "%s.\n\n", strings.TrimSuffix(strings.TrimSpace(root.Short), "."))
	}
	if flags := flagTable(root.PersistentFlags()); flags != "" {
		fmt.Fprintf(&index, "## Global flags\n\nEvery command takes these.\n\n%s\n", flags)
	}
	fmt.Fprintf(&index, "## Commands\n\n| Command | What it does |\n| --- | --- |\n")
	for _, c := range visible(root) {
		file := name + "-" + c.Name() + ".md"
		if len(visible(c)) == 0 {
			file = name + "-" + c.Name() + ".md"
		}
		fmt.Fprintf(&index, "| [`%s %s`](%s) | %s |\n", name, c.Name(), file, cell(c.Short))
		var page bytes.Buffer
		fmt.Fprintf(&page, "# `%s`\n\n<!-- Generated by `make docs` from the commands; do not edit. -->\n\n", c.CommandPath())
		fmt.Fprintf(&page, "[All commands](%s.md)\n\n", name)
		writeCommand(&page, c, 2)
		for _, sub := range visible(c) {
			writeTree(&page, sub, 2)
		}
		pages[file] = page.Bytes()
	}
	pages[name+".md"] = index.Bytes()
	return pages
}

func writeTree(b *bytes.Buffer, c *cobra.Command, level int) {
	writeCommand(b, c, level)
	for _, sub := range visible(c) {
		writeTree(b, sub, level+1)
	}
}

// writeCommand writes one command's section; a group without a run of its
// own gets its description and a list of its commands.
func writeCommand(b *bytes.Buffer, c *cobra.Command, level int) {
	if level > 2 || c.HasParent() && c.Parent().HasParent() {
		fmt.Fprintf(b, "%s `%s`\n\n", strings.Repeat("#", min(level, 4)), c.CommandPath())
	}
	desc := strings.TrimSpace(c.Long)
	if desc == "" {
		desc = strings.TrimSpace(c.Short)
		if desc != "" && !strings.HasSuffix(desc, ".") {
			desc += "."
		}
	}
	if desc != "" {
		fmt.Fprintf(b, "%s\n\n", desc)
	}
	if c.Runnable() {
		fmt.Fprintf(b, "```\n%s\n```\n\n", c.UseLine())
	}
	if len(c.Aliases) > 0 {
		fmt.Fprintf(b, "Also: `%s`.\n\n", strings.Join(c.Aliases, "`, `"))
	}
	if subs := visible(c); len(subs) > 0 && !c.Runnable() {
		fmt.Fprintf(b, "| Command | What it does |\n| --- | --- |\n")
		for _, s := range subs {
			fmt.Fprintf(b, "| [`%s`](#%s) | %s |\n", s.CommandPath(), anchor(s.CommandPath()), cell(s.Short))
		}
		b.WriteString("\n")
	}
	if c.Example != "" {
		fmt.Fprintf(b, "Examples:\n\n```bash\n%s\n```\n\n", strings.Trim(dedent(c.Example), "\n"))
	}
	if t := flagTable(c.LocalNonPersistentFlags()); t != "" && c.Runnable() {
		fmt.Fprintf(b, "Flags:\n\n%s\n", t)
	}
}

func visible(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, s := range c.Commands() {
		if s.IsAvailableCommand() && s.Name() != "help" && s.Name() != "completion" {
			out = append(out, s)
		}
	}
	slices.SortFunc(out, func(a, b *cobra.Command) int { return strings.Compare(a.Name(), b.Name()) })
	return out
}

func flagTable(fs *pflag.FlagSet) string {
	var rows []string
	fs.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Name == "help" {
			return
		}
		name := "`--" + f.Name
		if f.Shorthand != "" {
			name = "`-" + f.Shorthand + "`, " + name
		}
		varname, usage := pflag.UnquoteUsage(f)
		if varname != "" {
			name += " " + varname
		}
		name += "`"
		def := ""
		if f.Name == "config" {
			// Depends on the machine: see clientconfig.DefaultPath.
			f = &pflag.Flag{DefValue: "$ARMADA_CONFIG, else ~/.armada/config if it exists, else /etc/armada/admin.config"}
		}
		if f.DefValue != "" && f.DefValue != "false" && f.DefValue != "[]" && f.DefValue != "0" && f.DefValue != "0s" {
			def = " (default `" + f.DefValue + "`)"
		}
		rows = append(rows, "| "+name+" | "+cell(usage)+def+" |")
	})
	if len(rows) == 0 {
		return ""
	}
	return "| Flag | Meaning |\n| --- | --- |\n" + strings.Join(rows, "\n") + "\n"
}

func cell(s string) string {
	s = strings.ReplaceAll(strings.TrimSpace(s), "|", `\|`)
	return strings.ReplaceAll(s, "\n", " ")
}

// anchor is the heading anchor a Markdown renderer gives a command path.
func anchor(path string) string {
	return strings.ReplaceAll(strings.ToLower(path), " ", "-")
}

func dedent(s string) string {
	lines := strings.Split(s, "\n")
	pad := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " \t"))
		if pad < 0 || n < pad {
			pad = n
		}
	}
	for i, l := range lines {
		if len(l) >= pad && pad > 0 {
			lines[i] = l[pad:]
		}
	}
	return strings.Join(lines, "\n")
}

// Write writes pages into dir.
func Write(dir string, pages map[string][]byte) error {
	if err := os.MkdirAll(dir, 0o755); err != nil { //nolint:gosec // documentation, read by everyone
		return err
	}
	for name, b := range pages {
		if err := os.WriteFile(filepath.Join(dir, name), b, 0o644); err != nil { //nolint:gosec // documentation
			return err
		}
	}
	return nil
}
