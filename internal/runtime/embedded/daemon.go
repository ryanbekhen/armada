package embedded

import (
	"fmt"
	"net/netip"
	"path/filepath"
	"strconv"
	"strings"
)

// Namespace is the containerd namespace holding Armada's containers.
const Namespace = "armada"

// DefaultSubnet is the container bridge subnet unless configured otherwise.
var DefaultSubnet = netip.MustParsePrefix("10.121.0.0/24")

// BridgeName is the per-node container bridge.
const BridgeName = "armada0"

// Paths locates everything the embedded runtime keeps on disk.
type Paths struct {
	DataDir string // Armada's data directory, e.g. /var/lib/armada
	RunDir  string // e.g. /run/armada
}

// Bundle is where packs are extracted; Bin is the stable binary path.
func (p Paths) Bundle() string { return filepath.Join(p.DataDir, "runtime") }

// Bin holds containerd, the shim, runc, tini, and cni/.
func (p Paths) Bin() string { return filepath.Join(p.Bundle(), "current", "bin") }

// Root is containerd's persistent root (images, snapshots, metadata).
func (p Paths) Root() string { return filepath.Join(p.DataDir, "containerd") }

// State is containerd's runtime state.
func (p Paths) State() string { return filepath.Join(p.RunDir, "containerd") }

// Socket is containerd's gRPC socket.
func (p Paths) Socket() string { return filepath.Join(p.State(), "containerd.sock") }

// Config is containerd's configuration file.
func (p Paths) Config() string { return filepath.Join(p.Bundle(), "containerd.toml") }

// Logs holds container output.
func (p Paths) Logs() string { return filepath.Join(p.DataDir, "logs") }

// Containers holds per-container files (resolv.conf, hosts, hostname).
func (p Paths) Containers() string { return filepath.Join(p.DataDir, "containers") }

// CNI holds IPAM state and the plugin cache; on tmpfs because network
// namespaces do not survive a reboot either.
func (p Paths) CNI() string { return filepath.Join(p.RunDir, "cni") }

// NetNS holds the containers' pinned network namespaces.
func (p Paths) NetNS() string { return filepath.Join(p.RunDir, "netns") }

// FIFO holds the pipes of exec'd processes.
func (p Paths) FIFO() string { return filepath.Join(p.State(), "fifo") }

// disabledPlugins are containerd plugins Armada does not use. CRI would
// serve an extra API on the socket, NRI opens a socket of its own, and
// the TCP, debug, and metrics servers are listeners Armada never wants.
var disabledPlugins = []string{
	"io.containerd.grpc.v1.cri",
	"io.containerd.cri.v1.images",
	"io.containerd.cri.v1.runtime",
	"io.containerd.podsandbox.controller.v1.podsandbox",
	"io.containerd.nri.v1.nri",
	"io.containerd.server.v1.grpc-tcp",
	"io.containerd.server.v1.debug",
	"io.containerd.server.v1.metrics",
	"io.containerd.http.v1.pprof",
	// The agent recreates stopped containers itself (with crash backoff),
	// and pinned network namespaces do not survive a reboot.
	"io.containerd.monitor.container.v1.restart",
}

// ContainerdConfig renders containerd's configuration (format 4): its own
// root, state, and socket, nothing imported from the host's
// /etc/containerd, no listeners besides the socket.
func ContainerdConfig(p Paths) string {
	q := strconv.Quote
	var plugins []string
	for _, d := range disabledPlugins {
		plugins = append(plugins, q(d))
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by Armada (ADR 0011); changes are overwritten.\n")
	fmt.Fprintf(&b, "version = 4\n")
	fmt.Fprintf(&b, "root = %s\n", q(p.Root()))
	fmt.Fprintf(&b, "state = %s\n", q(p.State()))
	fmt.Fprintf(&b, "imports = []\n")
	fmt.Fprintf(&b, "disabled_plugins = [%s]\n\n", strings.Join(plugins, ", "))
	fmt.Fprintf(&b, "[plugins]\n")
	fmt.Fprintf(&b, "  [plugins.%s]\n    address = %s\n    uid = 0\n    gid = 0\n", q("io.containerd.server.v1.grpc"), q(p.Socket()))
	fmt.Fprintf(&b, "  [plugins.%s]\n    address = %s\n    uid = 0\n    gid = 0\n", q("io.containerd.server.v1.ttrpc"), q(p.Socket()+".ttrpc"))
	return b.String()
}
